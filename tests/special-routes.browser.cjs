'use strict';
const {chromium}=require(process.argv[2]);
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
const root=path.resolve(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'data.json'),'utf8'));
const config=JSON.parse(fs.readFileSync(path.join(root,'graph.json'),'utf8'));
const items=new Map([...data.stages,...data.entities].map(item=>[item.id,item]));
const allEdges=[...config.edges,...Object.values(config.expansions).flatMap(spec=>spec.edges)];
const link=(a,b)=>allEdges.find(edge=>edge.source===a&&edge.target===b);
assert.equal(config.edges.find(edge=>edge.id==='discussion-single-preview')?.kind,'preview','The collapsed map must expose the Congress single-reading alternative');
assert.equal(config.edges.find(edge=>edge.id==='senate-single-preview')?.kind,'preview');
assert.ok(items.get('discussion').mapNote?.loc&&items.get('senate').mapNote?.loc,'Timing notes need exact legal references');
assert.ok(link('senate','senate-reading-choice'));
assert.ok(link('senate-reading-choice','senate-single-reading'));
assert.ok(link('senate-reading-choice','senate-ordinary-review'));
assert.ok(link('senate-single-reading','return')&&link('senate-single-reading','king'));
assert.ok(!link('senate-single-reading','senate-review-amendments'),'Single reading permits veto proposals, not the ordinary amendment track');
assert.ok(!link('senate','senate-review-amendments'),'Ordinary work must follow the procedure choice');
assert.equal(link('single-reading','single-reading-rejected').mode,'ordinary');
assert.equal(link('single-reading','single-organic-report').mode,'organic','Single reading must preserve the organic reconsideration rule');
assert.ok(link('single-organic-report','single-organic-revote'));
assert.ok(link('single-organic-revote','senate')&&link('single-organic-revote','single-reading-rejected'));
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[],network=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
  await page.goto(pathToFileURL(path.join(root,'index.html')).href+'?lang=ru');
  assert.equal(await page.evaluate(()=>graph.whenReady()),true);
  let view=await page.evaluate(()=>graph.getVisibleGraph());
  assert.equal(view.nodes.length,8,'Overview must retain the compact stage list');
  for(const id of ['discussion-single-preview','senate-single-preview'])assert.ok(view.edges.some(edge=>edge.id===id));
  assert.match(view.nodes.find(node=>node.id==='discussion').label,/При срочности/);
  const initial=await page.evaluate(()=>graph.getState());
  await page.locator('[data-node-title="discussion"] [data-term="urgency"]').click();
  assert.match(await page.locator('#term-popover').textContent(),/не пропускает/);
  assert.ok(await page.locator('#term-popover [data-proof="008"]').count());
  assert.deepEqual(await page.evaluate(()=>graph.getState()),initial,'Timing explanations must not expand or move the map');
  await page.keyboard.press('Escape');
  await page.screenshot({path:path.join(root,'reports/short-procedures-overview.png')});
  await page.evaluate(()=>graph.toggle('senate'));view=await page.evaluate(()=>graph.getVisibleGraph());
  assert.ok(!view.edges.some(edge=>edge.id==='senate-single-preview'));
  assert.ok(view.edges.some(edge=>edge.source==='senate-reading-choice'&&edge.target==='senate-single-reading'));
  assert.ok(!view.nodes.some(node=>node.id==='reading-choice'),'Senate procedure choice is independent from Congress');
  await page.evaluate(()=>graph.activate('senate-single-reading'));
  assert.match(await page.locator('#detail-content').textContent(),/только предложения вето/);
  assert.ok(await page.locator('#detail-content [data-proof="010"]').count());
  await page.locator('#close-detail').click();
  await page.evaluate(()=>graph.toggle('discussion'));view=await page.evaluate(()=>graph.getVisibleGraph());
  assert.ok(!view.edges.some(edge=>edge.id==='discussion-single-preview'));
  assert.ok(view.edges.some(edge=>edge.source==='single-reading'&&edge.target==='senate'));
  await page.evaluate(()=>graph.fit());
  await page.screenshot({path:path.join(root,'reports/short-procedures-expanded.png')});
  await page.evaluate(()=>graph.toggle('return'));view=await page.evaluate(()=>graph.getVisibleGraph());
  assert.ok(view.edges.some(edge=>edge.source==='senate-single-reading'&&edge.target==='veto-first-vote'),'A known veto enters the Congress veto vote, not the amendment decision');
  await page.evaluate(()=>graph.showReturns(false));
  view=await page.evaluate(()=>graph.getVisibleGraph());
  assert.ok(!view.nodes.some(node=>node.id==='return'));
  await page.evaluate(()=>graph.reset());view=await page.evaluate(()=>graph.getVisibleGraph());
  assert.ok(view.edges.some(edge=>edge.id==='discussion-single-preview'),'Alternative preview is independent of the returns setting');
  for(const mode of ['ordinary','organic']){
   await page.evaluate(async mode=>{await graph.showReturns(true);await graph.setLawMode(mode);await graph.expandAll();},mode);
   view=await page.evaluate(()=>graph.getVisibleGraph());
   assert.equal(view.nodes.some(node=>node.id==='single-organic-report'),mode==='organic');
   assert.equal(view.edges.some(edge=>edge.source==='single-reading'&&edge.target==='single-reading-rejected'),mode==='ordinary');
   assert.ok(view.nodes.some(node=>node.id==='senate-single-reading'));
   for(const edge of view.edges)assert.ok(view.nodes.some(node=>node.id===edge.source)&&view.nodes.some(node=>node.id===edge.target));
  }
  assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
  console.log('PASS: visible short-route previews; independent Congress/Senate single reading; veto and organic safeguards; sourced timing explanations without reflow; filters; offline');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
